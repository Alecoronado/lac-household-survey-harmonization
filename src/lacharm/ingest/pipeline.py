"""Ingest step: raw fixed-width microdata -> typed Parquet, plus validation report."""

import logging
import zipfile
from dataclasses import dataclass
from pathlib import Path

import polars as pl

from lacharm.config import OfficialFigure, SurveyConfig
from lacharm.ingest.fixed_width import (
    detect_float_columns,
    find_data_member,
    iter_line_chunks,
    parse_chunk,
)
from lacharm.ingest.sas_input import parse_sas_input, record_length

logger = logging.getLogger(__name__)

DEFAULT_CHUNK_ROWS = 25_000


class IngestValidationError(RuntimeError):
    """An ingest validation failed; the Parquet output must not be trusted."""


@dataclass(frozen=True)
class IngestResult:
    survey_id: str
    year: int
    source_file: str
    n_columns: int
    record_length: int
    newline_bytes: int
    rows_expected: float  # from the archive size; fractional means a malformed file
    rows_read: int
    rows_written: int
    n_parts: int
    weight_variable: str
    weight_sum: float
    official_population: OfficialFigure | None

    @property
    def population_diff_pct(self) -> float | None:
        if self.official_population is None:
            return None
        official = self.official_population.value
        return 100 * (self.weight_sum - official) / official

    def failures(self) -> list[str]:
        problems = []
        if self.rows_expected != self.rows_read:
            problems.append(
                f"Row count mismatch: archive size implies {self.rows_expected} rows, "
                f"{self.rows_read} were read"
            )
        if self.rows_written != self.rows_read:
            problems.append(
                f"Row count mismatch: {self.rows_read} rows read, "
                f"{self.rows_written} found in the Parquet output"
            )
        return problems


def run_ingest(
    config: SurveyConfig,
    year: int,
    chunk_rows: int = DEFAULT_CHUNK_ROWS,
) -> IngestResult:
    """Convert one survey year to Parquet and validate the result.

    Raises :class:`IngestValidationError` if a validation fails. Lines with an
    unexpected width abort the run immediately (see ``parse_chunk``).
    """
    files = config.files_for(year)
    zip_path = config.raw_path(files.microdata_zip)
    specs = parse_sas_input(config.raw_path(files.sas_input), config.encoding.sas_input)
    width = record_length(specs)
    member = find_data_member(zip_path)
    weight = config.design.person_weight
    if weight not in {spec.name for spec in specs}:
        raise KeyError(f"Weight variable {weight!r} is not in the SAS input file")

    logger.info("Source: %s (%s, %d bytes)", zip_path.name, member.name, member.size_bytes)
    logger.info("Layout: %d columns, record length %d", len(specs), width)

    output_dir = config.interim_path(year)
    _prepare_output_dir(output_dir)

    rows_read = 0
    weight_sum = 0.0
    n_parts = 0
    float_columns: set[str] | None = None
    newline_bytes = _newline_length(zip_path, member.name)

    chunks = iter_line_chunks(zip_path, member.name, config.encoding.microdata, chunk_rows)
    for lines in chunks:
        if float_columns is None:
            float_columns = detect_float_columns(lines, specs)
            logger.info("Decimal columns detected: %d", len(float_columns))
        frame = parse_chunk(lines, specs, float_columns)
        frame.write_parquet(output_dir / f"part-{n_parts:05d}.parquet", compression="zstd")
        rows_read += frame.height
        weight_sum += frame[weight].sum()
        n_parts += 1
        logger.info("Wrote part %d (%d rows so far)", n_parts, rows_read)

    result = IngestResult(
        survey_id=config.survey_id,
        year=year,
        source_file=files.microdata_zip,
        n_columns=len(specs),
        record_length=width,
        newline_bytes=newline_bytes,
        rows_expected=member.size_bytes / (width + newline_bytes),
        rows_read=rows_read,
        rows_written=_count_parquet_rows(output_dir),
        n_parts=n_parts,
        weight_variable=weight,
        weight_sum=weight_sum,
        official_population=files.official_population,
    )

    failures = result.failures()
    if failures:
        raise IngestValidationError("; ".join(failures))
    return result


def write_report(result: IngestResult, specs_path: str, report_path: Path) -> None:
    """Write the validation results as a small Markdown report (aggregates only)."""
    lines = [
        f"# Ingest report: {result.survey_id} {result.year}",
        "",
        "Generated by `lacharm ingest`. Contains aggregates only, no microdata.",
        "",
        "## Source",
        "",
        f"- Microdata archive: `{result.source_file}`",
        f"- Column layout: `{specs_path}`",
        f"- Columns: {result.n_columns}",
        f"- Record length: {result.record_length} characters "
        f"(+ {result.newline_bytes} line-terminator byte(s))",
        "",
        "## Validations",
        "",
        "| Check | Expected | Observed | Result |",
        "|---|---|---|---|",
        f"| Rows read vs rows implied by file size | {result.rows_expected:,.0f} "
        f"| {result.rows_read:,} | PASS |",
        f"| Rows in Parquet vs rows read | {result.rows_read:,} | {result.rows_written:,} | PASS |",
        "| Lines with unexpected width | 0 | 0 | PASS |",
        "",
        "A line with the wrong width aborts the run, so a generated report implies zero.",
        "",
        "## Weights vs official population",
        "",
    ]
    official = result.official_population
    if official is None:
        lines.append("No official population figure is configured for this year.")
    else:
        lines += [
            "| Quantity | Value |",
            "|---|---|",
            f"| Sum of `{result.weight_variable}` | {result.weight_sum:,.0f} |",
            f"| Official population | {official.value:,.0f} |",
            f"| Difference | {result.weight_sum - official.value:+,.0f} persons "
            f"({result.population_diff_pct:+.5f}%) |",
            "",
            f"Source: {official.source}. Consulted {official.consulted.isoformat()}.",
            f"<{official.url}>",
        ]
    lines += ["", "## Output", "", f"- Parquet parts: {result.n_parts} (zstd)", ""]
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def _prepare_output_dir(output_dir: Path) -> None:
    """Create the output folder and remove parts left by a previous run."""
    output_dir.mkdir(parents=True, exist_ok=True)
    for stale in output_dir.glob("part-*.parquet"):
        stale.unlink()


def _newline_length(zip_path: Path, member: str) -> int:
    """Bytes used by the line terminator (1 for LF, 2 for CRLF)."""
    with zipfile.ZipFile(zip_path) as archive, archive.open(member) as stream:
        first_line = stream.readline()
    return len(first_line) - len(first_line.rstrip(b"\r\n"))


def _count_parquet_rows(output_dir: Path) -> int:
    """Count rows by reading the Parquet files back, independently of the writer loop."""
    return pl.scan_parquet(output_dir / "part-*.parquet").select(pl.len()).collect().item()
