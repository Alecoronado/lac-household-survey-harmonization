"""Catalog step: publisher's dictionary -> structured variable catalog + discrepancy report."""

import logging
from dataclasses import dataclass
from pathlib import Path

import polars as pl

from lacharm.config import SurveyConfig
from lacharm.ingest.sas_input import parse_sas_input
from lacharm.metadata.catalog import CatalogEntry, catalog_to_frame, write_catalog_json
from lacharm.metadata.compare import (
    CodeComparison,
    LayoutComparison,
    compare_with_data,
    compare_with_input,
)
from lacharm.metadata.ibge_dictionary import DictionaryLayout, parse_dictionary

logger = logging.getLogger(__name__)

_MAX_REPORT_ROWS = 60


@dataclass(frozen=True)
class CatalogResult:
    survey_id: str
    year: int
    entries: list[CatalogEntry]
    layout: LayoutComparison
    codes: list[CodeComparison] | None  # None when the ingested data are not available
    json_path: Path
    parquet_path: Path


def run_catalog(config: SurveyConfig, year: int) -> CatalogResult:
    """Build the catalog for one survey year and cross-check it."""
    files = config.files_for(year)
    layout = DictionaryLayout(**config.dictionary.model_dump())
    entries = parse_dictionary(config.raw_path(files.dictionary), layout, year)
    specs = parse_sas_input(config.raw_path(files.sas_input), config.encoding.sas_input)

    # The SAS program's short description complements the dictionary label
    # (and is the only description when the dictionary leaves the label empty).
    sas_labels = {spec.name: spec.description for spec in specs}
    entries = [
        entry.model_copy(update={"sas_label": sas_labels.get(entry.variable) or None})
        for entry in entries
    ]

    json_path = config.catalog_dir / f"{config.survey_id}_{year}.json"
    parquet_path = config.interim_dir / f"catalog_{year}.parquet"
    write_catalog_json(entries, json_path)
    parquet_path.parent.mkdir(parents=True, exist_ok=True)
    catalog_to_frame(entries).write_parquet(parquet_path, compression="zstd")
    logger.info("Catalog: %d variables -> %s", len(entries), json_path)

    data_dir = config.interim_path(year)
    codes = None
    if any(data_dir.glob("part-*.parquet")):
        codes = compare_with_data(entries, pl.scan_parquet(data_dir / "part-*.parquet"))
    else:
        logger.warning("No ingested data in %s: codes were not checked against data", data_dir)

    return CatalogResult(
        survey_id=config.survey_id,
        year=year,
        entries=entries,
        layout=compare_with_input(entries, specs),
        codes=codes,
        json_path=json_path,
        parquet_path=parquet_path,
    )


def write_report(result: CatalogResult, report_path: Path) -> None:
    """Write the catalog summary and every discrepancy found (aggregates only)."""
    entries, layout = result.entries, result.layout
    lines = [
        f"# Catalog report: {result.survey_id} {result.year}",
        "",
        "Generated by `lacharm catalog`. Contains aggregates only, no microdata.",
        "",
        "## Catalog",
        "",
        "| | |",
        "|---|---|",
        f"| Variables | {len(entries)} |",
        f"| With categories (coded) | {sum(bool(e.categories) for e in entries)} |",
        f"| With a range or unit instead of codes | {sum(bool(e.value_note) for e in entries)} |",
        f"| With a free-text remark | {sum(bool(e.remark) for e in entries)} |",
        f'| With a "not applicable" category | {sum(e.has_not_applicable for e in entries)} |',
        f"| With an explicit universe | {sum(e.universe is not None for e in entries)} |",
        f"| Category labels in total | {sum(len(e.categories) for e in entries)} |",
        "",
        "### Variables per module",
        "",
        "| Module | Variables |",
        "|---|---|",
    ]
    modules: dict[str, int] = {}
    for entry in entries:
        modules[entry.module or "(none)"] = modules.get(entry.module or "(none)", 0) + 1
    lines += [f"| {module} | {count} |" for module, count in modules.items()]

    lines += [
        "",
        "## Dictionary vs SAS input program",
        "",
        f"Coverage: **{layout.coverage_pct:.1f}%** of the {layout.n_input} variables in the "
        "input program are documented in the dictionary.",
        "",
        "| Check | Count | Variables |",
        "|---|---|---|",
        _check_row("In the input program, missing from the dictionary", layout.only_in_input),
        _check_row("In the dictionary, missing from the input program", layout.only_in_dictionary),
        _check_row("Start position or width differ", layout.position_mismatches),
        _check_row("Dictionary label is empty", layout.without_label),
    ]

    lines += ["", "## Dictionary codes vs values in the data", ""]
    if result.codes is None:
        lines.append("Not run: the ingested data were not available.")
    else:
        lines += _code_sections(result.codes)

    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")


def _check_row(label: str, items: list[str]) -> str:
    return f"| {label} | {len(items)} | {', '.join(items) or '-'} |"


def _code_sections(codes: list[CodeComparison]) -> list[str]:
    undocumented = [c for c in codes if c.undocumented and c.value_note is None]
    ranged = [c for c in codes if c.value_note is not None]
    unused = [c for c in codes if c.unused]
    blanks = [c for c in codes if c.blank_not_documented]

    lines = [
        f"Checked {len(codes)} coded variables.",
        "",
        "| Check | Variables affected |",
        "|---|---|",
        f"| Values in the data that the dictionary does not list | {len(undocumented)} |",
        f"| Variables that combine a range with special codes | {len(ranged)} |",
        f"| Documented codes that never occur in the data | {len(unused)} |",
        f'| Blank values without a "not applicable" category | {len(blanks)} |',
        "",
        "### Values in the data that the dictionary does not list",
        "",
    ]
    if undocumented:
        lines += ["| Variable | Value | Rows |", "|---|---|---|"]
        rows = [
            f"| {c.variable} | `{code}` | {count:,} |"
            for c in undocumented
            for code, count in c.undocumented.items()
        ]
        lines += _truncate(rows)
    else:
        lines.append("None.")

    lines += ["", "### Variables that combine a range with special codes", ""]
    if ranged:
        lines += [
            "The dictionary gives a range plus a few codes (for example, day of birth "
            "`01 a 31` plus `99`). Values outside the listed codes are expected here, "
            "so they are counted, not listed.",
            "",
            "| Variable | Range or unit in the dictionary | Distinct other values | Rows |",
            "|---|---|---|---|",
        ]
        lines += [
            f"| {c.variable} | {c.value_note} | {len(c.undocumented)} "
            f"| {sum(c.undocumented.values()):,} |"
            for c in ranged
        ]
    else:
        lines.append("None.")

    lines += ["", "### Documented codes that never occur in the data", ""]
    if unused:
        lines += [
            "Not an error: a category can simply have no respondents in a given year.",
            "",
            "| Variable | Codes |",
            "|---|---|",
        ]
        lines += _truncate([f"| {c.variable} | {', '.join(c.unused)} |" for c in unused])
    else:
        lines.append("None.")

    lines += ["", '### Blank values without a "not applicable" category', ""]
    if blanks:
        lines += ["| Variable | Blank rows |", "|---|---|"]
        lines += _truncate([f"| {c.variable} | {c.null_rows:,} |" for c in blanks])
    else:
        lines.append("None.")
    return lines


def _truncate(rows: list[str]) -> list[str]:
    if len(rows) <= _MAX_REPORT_ROWS:
        return rows
    hidden = len(rows) - _MAX_REPORT_ROWS
    return [*rows[:_MAX_REPORT_ROWS], "", f"... and {hidden} more rows not shown."]
